const LanguageContext = createContext<I18n | null>(null);
const STORAGE_KEY = "ux_language";

function languageStorage(): Storage {
  try {
    if (window.localStorage) return window.localStorage;
  } catch { /* Restricted browser contexts can disable local storage. */ }
  return window.sessionStorage;
}

function savedLanguage(): Language {
  return languageStorage().getItem(STORAGE_KEY) === "zh" ? "zh" : "en";
}

export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<Language>(savedLanguage);
  const setLanguage = (next: Language) => {
    languageStorage().setItem(STORAGE_KEY, next);
    setLanguageState(next);
  };
  useEffect(() => { document.documentElement.lang = language === "zh" ? "zh-CN" : "en"; }, [language]);
  const value = useMemo<I18n>(() => ({
    language,
    setLanguage,
    t: (text, values = {}) => {
      const translated = language === "zh" ? translations[text] || assistantTranslations[text] || text : englishLabels[text] || text;
      return translated.replace(/\{(\w+)\}/g, (_match, key: string) => String(values[key] ?? `{${key}}`));
    },
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function LanguageToggle() {
  const { language, setLanguage } = useI18n();
  return <div className="language-toggle" role="group" aria-label={language === "zh" ? "语言 / Language" : "Language / 语言"}>
    <button type="button" aria-pressed={language === "zh"} className={language === "zh" ? "active" : ""} onClick={() => setLanguage("zh")}>中文</button>
    <button type="button" aria-pressed={language === "en"} className={language === "en" ? "active" : ""} onClick={() => setLanguage("en")}>EN</button>
  </div>;
}

export function useI18n() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}
